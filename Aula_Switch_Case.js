//Aula Switch Case

let dia = "sexta-feira";

switch(dia) {
    case "segunda-feira":
        console.log("Hoje é segunda-feira, início da semana!");
        break;
    case "terça-feira":
        console.log("Hoje é terça-feira, vamos continuar!");
        break;
    case "quarta-feira":
        console.log("Hoje é quarta-feira, estamos no meio da semana!");
        break;
    case "quinta-feira":
        console.log("Hoje é quinta-feira, quase lá!");
        break;
    case "sexta-feira":
        console.log("Hoje é sexta-feira, o fim de semana está chegando!");
        break;
    default:
        console.log("Final de Semana!");
}
